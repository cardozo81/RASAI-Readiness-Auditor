"""Operational GeoIP locations and bounded maintenance, outside audit execution.

No credentials, downloads, or licensed MMDB are generated by this module.
Installation of the verified official binary remains a separate bootstrap action.
"""
from __future__ import annotations

from datetime import datetime, timezone
import os
from pathlib import Path
import subprocess
import sys


def operational_home() -> Path:
    """A writable per-user RASAi home, independent of repository permissions."""
    if sys.platform == "win32":
        root = os.environ.get("LOCALAPPDATA")
        if root:
            return Path(root) / "RASAi"
    return Path.home() / ".local" / "share" / "rasai"


def database_directory() -> Path:
    return operational_home() / "data" / "geoip"


def updater_executable() -> Path:
    name = "geoipupdate.exe" if sys.platform == "win32" else "geoipupdate"
    return operational_home() / "tools" / "geoipupdate" / name


def local_databases() -> dict[str, str | None]:
    """Existing, regular databases only. Never search arbitrary global paths."""
    root = database_directory()
    paths = {"city_database": root / "GeoLite2-City.mmdb",
             "asn_database": root / "GeoLite2-ASN.mmdb"}
    return {key: str(path) if path.is_file() and not path.is_symlink() else None
            for key, path in paths.items()}


def run_authorized_update(config: Path, *, licensed: bool, timeout: int = 120) -> dict:
    """Invoke only the RASAi-owned binary, outside AUD/RPR/CONS.

    Credentials live in operator-managed protected configuration. Neither the
    configuration content nor stderr are persisted or returned.
    """
    exe = updater_executable()
    if not licensed:
        return {"state": "NOT_CONFIGURED", "error": "LICENSE_NOT_CONFIRMED"}
    if not exe.is_file() or exe.is_symlink() or not config.is_file() or config.is_symlink():
        return {"state": "NOT_CONFIGURED", "error": "UPDATER_OR_CONFIG_MISSING"}
    if type(timeout) is not int or not 1 <= timeout <= 120:
        raise ValueError("Orçamento de atualização inválido")
    target = database_directory()
    target.mkdir(parents=True, exist_ok=True)
    try:
        # geoipupdate official CLI accepts -f (config) and -d (database dir).
        result = subprocess.run([str(exe), "-f", str(config), "-d", str(target)],
                                capture_output=True, timeout=timeout, check=False)
    except (OSError, subprocess.TimeoutExpired):
        return {"state": "FAILED", "error": "UPDATER_EXECUTION_FAILED"}
    return {"state": "UPDATED" if result.returncode == 0 else "FAILED",
            "error": None if result.returncode == 0 else "UPDATER_NONZERO_EXIT",
            "checked_utc": datetime.now(timezone.utc).isoformat()}
