"""Operational GeoIP locations and bounded maintenance, outside audit execution.

No credentials, downloads, or licensed MMDB are generated by this module.
Installation of the verified official binary remains a separate bootstrap action.
"""
from __future__ import annotations

from datetime import datetime, timezone
import os
import importlib
from pathlib import Path
import subprocess
import sys


def operational_home() -> Path:
    """A writable per-user RASAi home, independent of repository permissions."""
    if sys.platform == "win32":
        root = os.environ.get("LOCALAPPDATA")
        if root:
            return Path(root) / "RASAi"
    return Path.home() / ".local" / "share" / "rasai"


def application_directory() -> Path:
    """Return the RASAi program checkout, independent of current directory.

    Editable-install source lives in <RASAI_ROOT>/src/rasai.
    """
    return Path(__file__).resolve().parents[2]


def database_directory() -> Path:
    """City/ASN MMDBs live alongside the RASAi application, never in AppData."""
    return application_directory() / "data" / "geoip"


def updater_executable() -> Path:
    name = "geoipupdate.exe" if sys.platform == "win32" else "geoipupdate"
    return operational_home() / "tools" / "geoipupdate" / name


def _database_category(database_type: object) -> str | None:
    """Classify by MMDB metadata, not by its operator-controlled filename."""
    if not isinstance(database_type, str):
        return None
    label = database_type.strip().casefold()
    if label.endswith("-city"):
        return "city_database"
    if label.endswith("-asn"):
        return "asn_database"
    return None


def local_databases() -> dict[str, str | None]:
    """Discover at most two MMDBs by verified content, regardless of filename.

    Independent City/ASN coverage is preserved when one is absent or invalid.
    More than two MMDB files, or duplicate databases for one role, cannot be
    resolved deterministically and are rejected without blocking the audit.
    """
    resolved: dict[str, str | None] = {
        "city_database": None, "asn_database": None,
    }
    root = database_directory()
    if root.is_symlink() or root.parent.is_symlink() or not root.is_dir():
        return resolved

    try:
        candidates = []
        with os.scandir(root) as directory:
            for item in directory:
                if item.name.casefold().endswith(".mmdb"):
                    candidates.append(Path(item.path))
                    if len(candidates) > 2:
                        return resolved
    except OSError:
        return resolved
    if not candidates:
        return resolved

    try:
        mmdb = importlib.import_module("maxminddb")
    except ImportError:
        return resolved

    ambiguous: set[str] = set()
    for path in sorted(candidates, key=lambda item: item.name.casefold()):
        try:
            if path.is_symlink() or not path.is_file():
                continue
            size = path.stat().st_size
            if not 1 <= size <= 180_000_000:
                continue
            reader = mmdb.open_database(str(path))
            try:
                metadata = reader.metadata()
                category = _database_category(metadata.database_type)
                if category is None or type(metadata.build_epoch) is not int or metadata.build_epoch <= 0:
                    continue
            finally:
                reader.close()
            if category in ambiguous:
                continue
            if resolved[category] is not None:
                resolved[category] = None
                ambiguous.add(category)
            else:
                resolved[category] = str(path)
        except (OSError, ValueError, TypeError, AttributeError):
            continue
    return resolved


def run_authorized_update(config: Path, *, licensed: bool, timeout: int = 120) -> dict:
    """Invoke only the RASAi-owned binary, outside AUD/RPR/CONS.

    Credentials live in operator-managed protected configuration. Neither the
    configuration content nor stderr are persisted or returned.
    """
    exe = updater_executable()
    if not licensed:
        return {"state": "NOT_CONFIGURED", "error": "LICENSE_NOT_CONFIRMED"}
    if not exe.is_file() or exe.is_symlink() or not config.is_file() or config.is_symlink():
        return {"state": "NOT_CONFIGURED", "error": "UPDATER_OR_CONFIG_MISSING"}
    if type(timeout) is not int or not 1 <= timeout <= 120:
        raise ValueError("Orçamento de atualização inválido")
    target = database_directory()
    try:
        # A read-only application installation is non-blocking for any audit.
        if target.is_symlink() or target.parent.is_symlink():
            return {"state": "FAILED", "error": "UNSAFE_DATABASE_DIRECTORY"}
        target.mkdir(parents=True, exist_ok=True)
        # geoipupdate official CLI accepts -f (config) and -d (database dir).
        result = subprocess.run([str(exe), "-f", str(config), "-d", str(target)],
                                capture_output=True, timeout=timeout, check=False)
    except (OSError, subprocess.TimeoutExpired):
        return {"state": "FAILED", "error": "UPDATER_EXECUTION_FAILED"}
    return {"state": "UPDATED" if result.returncode == 0 else "FAILED",
            "error": None if result.returncode == 0 else "UPDATER_NONZERO_EXIT",
            "checked_utc": datetime.now(timezone.utc).isoformat()}
